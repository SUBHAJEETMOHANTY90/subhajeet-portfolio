/**
 * Markdown report renderer.
 *
 * Output is intentionally Markdown so the same artifact can be:
 *   - written to the GitHub Actions job summary ($GITHUB_STEP_SUMMARY)
 *   - posted as a PR comment
 *   - pushed to Teams/Slack
 *   - converted to PDF
 */

export function renderReport({ meta, gate, k6, server, traces, findings, narrative }) {
  const c = k6?.metrics ?? {};
  const s = server?.metrics ?? {};
  const badge = gate.verdict === "PASS" ? "✅ PASS" : "❌ FAIL";

  const out = [];

  out.push(`# Performance Report — ${meta.service}`, "");
  out.push(`> **Verdict: ${badge}**  ·  ${meta.environment}  ·  ${meta.testScript}`, "");
  out.push(
    `| Run | Value |`,
    `| --- | --- |`,
    `| Environment | ${meta.environment} |`,
    `| Service | ${meta.service} |`,
    `| Test script | ${meta.testScript} |`,
    `| Virtual users | ${meta.vus ?? "n/a"} |`,
    `| Ramp-up / Duration | ${meta.rampUp ?? "n/a"} / ${meta.duration ?? "n/a"} |`,
    `| Window | ${meta.start} → ${meta.end} |`,
    ""
  );

  // ---- SLA gate -----------------------------------------------------
  out.push(`## SLA gate (deterministic)`, "");
  out.push(`| Metric | Actual | SLA | Result |`, `| --- | --- | --- | --- |`);
  for (const chk of gate.checks) {
    const icon = chk.status === "PASS" ? "✅" : chk.status === "FAIL" ? "❌" : "⚠️";
    const delta = chk.deltaPct != null ? ` (${chk.deltaPct > 0 ? "+" : ""}${chk.deltaPct}%)` : "";
    out.push(
      `| ${chk.label ?? chk.metric} | ${chk.actual ?? "n/a"}${delta} | ${chk.op} ${chk.value} | ${icon} ${chk.status} |`
    );
  }
  out.push("");

  // ---- Side-by-side client vs server --------------------------------
  out.push(`## Client-side vs server-side`, "");
  out.push(`| Signal | Client (k6) | Server (OTel / SignalFx) |`, `| --- | --- | --- |`);
  out.push(`| p95 latency | ${fmt(c.p95_ms, "ms")} | ${fmt(s.server_p95_ms, "ms")} |`);
  out.push(`| p99 latency | ${fmt(c.p99_ms, "ms")} | ${fmt(s.server_p99_ms, "ms")} |`);
  out.push(`| Throughput | ${fmt(c.tps, "req/s")} | ${fmt(s.server_rps, "req/s")} |`);
  out.push(`| Error rate | ${pct(c.error_rate)} | ${pct(s.server_error_rate)} |`);
  out.push("");

  // ---- Server-side detail -------------------------------------------
  out.push(`## Server-side resource &amp; runtime`, "");
  out.push(`| Metric | Value |`, `| --- | --- |`);
  const rows = [
    ["CPU utilisation", fmt(s.cpu_utilization_pct, "%")],
    ["CPU throttling", fmt(s.cpu_throttle_pct, "%")],
    ["Memory working set", fmt(s.memory_working_set_mb, "MB")],
    ["Heap used", fmt(s.heap_used_pct, "%")],
    ["GC pause p95", fmt(s.gc_pause_p95_ms, "ms")],
    ["Event-loop lag p95", fmt(s.eventloop_lag_p95_ms, "ms")],
    ["DB p95", fmt(s.db_p95_ms, "ms")],
    ["Downstream HTTP p95", fmt(s.downstream_p95_ms, "ms")],
    ["Connection pool saturation", fmt(s.connection_pool_saturation_pct, "%")],
    ["Max ready pods", fmt(s.pod_count_max)],
    ["Pod restarts", fmt(s.pod_restarts)],
  ].filter(([, v]) => v !== "n/a");
  if (rows.length) rows.forEach(([k, v]) => out.push(`| ${k} | ${v} |`));
  else out.push(`| _no server-side metrics available_ | |`);
  out.push("");

  // ---- Traces --------------------------------------------------------
  if (traces?.topSpans?.length) {
    out.push(`## Hottest operations (traces)`, "");
    out.push(`| Operation | Count | p95 | Max | Total |`, `| --- | --- | --- | --- | --- |`);
    for (const t of traces.topSpans.slice(0, 5)) {
      out.push(`| \`${t.name}\` | ${t.count} | ${t.p95_ms} ms | ${t.max_ms} ms | ${t.total_ms} ms |`);
    }
    out.push("");
  }

  // ---- Correlated findings ------------------------------------------
  out.push(`## Correlated findings`, "");
  if (findings.length) {
    for (const f of findings) {
      out.push(`### ${sev(f.severity)} ${f.title}`);
      out.push(`- **Evidence:** ${f.evidence}`);
      out.push(`- **Hypothesis:** ${f.hypothesis}`);
      out.push(`- **Action:** ${f.action}`, "");
    }
  } else {
    out.push("_No notable correlations detected._", "");
  }

  // ---- AI narrative --------------------------------------------------
  out.push(`---`, "", `# AI analysis`, "");
  out.push(narrative || "_No narrative generated._", "");

  out.push(
    `---`,
    "",
    `<sub>Generated by \`perf-ai-report\` · verdict decided by deterministic SLA thresholds; AI used for explanation only.</sub>`
  );

  return out.join("\n");
}

const sev = (s) => (s === "HIGH" ? "🔴" : s === "MEDIUM" ? "🟠" : s === "LOW" ? "🟡" : "🔵");
const fmt = (v, unit = "") => (v === null || v === undefined ? "n/a" : `${v}${unit ? " " + unit : ""}`);
const pct = (v) => (v === null || v === undefined ? "n/a" : `${(Number(v) * 100).toFixed(2)}%`);
